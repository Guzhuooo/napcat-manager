#!/bin/sh
# ============================================================================
#  NapCat 启动（被管理器 native 模块调用，也可手动执行）
#
#  用法: sh start-napcat.sh [QQ号]
#    - 带参数: 用该 QQ 快速登录
#    - 无参数: 用 state/account 里记住的账号快速登录；都没有则二维码
#
#  全部逻辑委托给 napcat-ctl.sh，保持单一实现。
# ============================================================================
exec sh /userdisk/napcat/bin/napcat-ctl.sh start "${1:-}"
